// 7. دالة إنشاء تقرير الغياب اليومي
// ==========================================
function generateDailyReport() {
    const reportContainer = document.getElementById('report-container');
    reportContainer.innerHTML = ''; 

    let savedData = JSON.parse(localStorage.getItem('attendanceData')) || {};
    let absentees = [];

    for (const [studentId, status] of Object.entries(savedData)) {
        if (status === 'absent') {
            const parts = studentId.split('_');
            const className = parts[0]; 
            const lessonNum = parts[1];
            const studentName = parts.slice(3).join('_'); 
            
            absentees.push({ className, lessonNum, studentName });
        }
    }

    if (absentees.length === 0) {
        reportContainer.innerHTML = `
            <div class="no-absences">
                ✅ لا يوجد أي غياب مسجل حتى الآن لهذا اليوم.
            </div>
        `;
        return;
    }

    absentees.sort((a, b) => {
        if (a.className !== b.className) return a.className.localeCompare(b.className, undefined, {numeric: true});
        return parseInt(a.lessonNum) - parseInt(b.lessonNum);
    });

    let tableHTML = `
        <table class="report-table">
            <thead>
                <tr>
                    <th>م</th>
                    <th>الصف / الشعبة</th>
                    <th>الحصة</th>
                    <th>اسم الطالب</th>
                    <th>الحالة</th>
                </tr>
            </thead>
            <tbody>
    `;

    absentees.forEach((student, index) => {
        tableHTML += `
            <tr>
                <td>${index + 1}</td>
                <td><strong>شعبة ${student.className}</strong></td>
                <td>الحصة ${student.lessonNum}</td>
                <td>${student.studentName}</td>
                <td style="color: red; font-weight: bold;">غائب</td>
            </tr>
        `;
    });

    tableHTML += `
            </tbody>
        </table>
        <p style="text-align: left; margin-top: 10px; font-weight: bold;">
            إجمالي عدد الغائبين: ${absentees.length} طالب
        </p>
    `;

    reportContainer.innerHTML = tableHTML;
}

