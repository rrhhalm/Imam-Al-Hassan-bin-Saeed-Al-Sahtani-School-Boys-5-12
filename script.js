function loadAllAbsences() {
    const container = document.getElementById('social-report-container');
    container.innerHTML = '';
    
    let savedData = JSON.parse(localStorage.getItem('attendanceData')) || {};
    let absentees = [];

    for (const [studentId, status] of Object.entries(savedData)) {
        if (status === 'absent') {
            const parts = studentId.split('_');
            const className = parts[0]; 
            const lessonNum = parts[1];
            const studentName = parts.slice(3).join('_'); 
            
            absentees.push({ 
                id: studentId, 
                className, 
                lessonNum,
                studentName 
            });
        }
    }

    if (absentees.length === 0) {
        container.innerHTML = `<div class="no-absences">لا يوجد أي غياب مسجل حالياً.</div>`;
        return;
    }

    absentees.sort((a, b) => a.className.localeCompare(b.className, undefined, {numeric: true}));

    let tableHTML = `
        <table class="report-table">
            <thead>
                <tr>
                    <th>م</th>
                    <th>الصف / الشعبة</th>
                    <th>الحصة</th>
                    <th>اسم الطالب</th>
                    <th>إجراء</th>
                </tr>
            </thead>
            <tbody>
    `;

    absentees.forEach((student, index) => {
        tableHTML += `
            <tr>
                <td>${index + 1}</td>
                <td><strong>شعبة ${student.className}</strong></td>
                <td>الحصة ${student.lessonNum}</td>
                <td>${student.studentName}</td>
                <td>
                    <button onclick="deleteAbsence('${student.id}')" style="background: #c62828; color: white; border: none; padding: 5px 10px; border-radius: 5px; cursor: pointer;">حذف</button>
                </td>
            </tr>
        `;
    });

    tableHTML += `</tbody></table>`;
    container.innerHTML = tableHTML;
}

function deleteAbsence(studentId) {
    if (confirm("هل أنت متأكد من حذف سجل الغياب هذا؟")) {
        let savedData = JSON.parse(localStorage.getItem('attendanceData')) || {};
        delete savedData[studentId];
        localStorage.setItem('attendanceData', JSON.stringify(savedData));
        
        alert("تم حذف السجل بنجاح!");
        loadAllAbsences();
    }
}

function clearAllAbsences() {
    if (confirm("⚠️ تحذير: هذا الإجراء سيقوم بمسح جميع سجلات الغياب لجميع الشعب. هل أنت متأكد؟")) {
        localStorage.removeItem('attendanceData');
        alert("تم مسح جميع السجلات بنجاح!");
        document.getElementById('social-report-container').innerHTML = `<div class="no-absences">لا يوجد أي غياب مسجل حالياً.</div>`;
    }
}