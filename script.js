function openSection(sectionId) {
    document.querySelectorAll('.section-content').forEach(sec => sec.classList.remove('active'));
    document.querySelectorAll('.card-btn').forEach(btn => btn.style.display = 'none');
    document.getElementById(sectionId).classList.add('active');
}

function closeSection(sectionId) {
    document.getElementById(sectionId).classList.remove('active');
    
    // إظهار جميع الأزرار
    document.querySelectorAll('.card-btn').forEach(btn => btn.style.display = 'block');
    
    // إخفاء زر الأخصائي إذا لم يكن المستخدم أخصائياً
    const role = localStorage.getItem('userRole');
    if (role !== 'social_worker') {
        const socialBtn = document.getElementById('btn-social');
        if (socialBtn) socialBtn.style.display = 'none';
    }
}

