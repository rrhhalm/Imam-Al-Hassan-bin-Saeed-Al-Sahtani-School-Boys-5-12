// 5.5. دالة الحفظ (المحدثة للربط مع جوجل)
// ==========================================
function saveAttendance(className) {
    // 1. جمع البيانات من الجلسة الحالية
    let tempData = JSON.parse(sessionStorage.getItem('tempAttendance')) || {};
    
    // 2. تصفية الغائبين فقط لإرسالهم إلى جوجل شيتس
    let absenteesToSend = [];
    
    for (const [studentId, status] of Object.entries(tempData)) {
        if (status === 'absent') {
            const parts = studentId.split('_');
            const classId = parts[0];       // الشعبة
            const lessonNum = parts[1];     // الحصة
            const studentName = parts.slice(3).join('_'); // الاسم
            
            absenteesToSend.push({
                className: classId,
                lesson: lessonNum,
                studentName: studentName,
                status: 'غائب'
            });
        }
    }

    // 3. الحفظ المحلي (احتياطي) في المتصفح
    let permanentData = JSON.parse(localStorage.getItem('attendanceData')) || {};
    Object.assign(permanentData, tempData);
    localStorage.setItem('attendanceData', JSON.stringify(permanentData));

    // 4. إرسال البيانات إلى جوجل شيتس باستخدام no-cors لتجنب الحظر
    if (absenteesToSend.length > 0) {
        alert(`جاري إرسال ${absenteesToSend.length} غائب إلى السجل السحابي...`);

        absenteesToSend.forEach(student => {
            fetch(GOOGLE_SCRIPT_URL, {
                method: 'POST',
                mode: 'no-cors', // هذا هو الحل السحري
                headers: {
                    'Content-Type': 'text/plain;charset=utf-8'
                },
                body: JSON.stringify(student)
            })
            .then(() => {
                // مع no-cors لا يمكن قراءة الرد، لكن الطلب يُرسل بنجاح
                console.log('تم إرسال البيانات إلى جوجل شيتس.');
            })
            .catch(error => {
                console.error('خطأ في الإرسال:', error);
            });
        });
        
        // ننتظر ثانيتين لضمان وصول البيانات ثم نبلغ المستخدم
        setTimeout(() => {
            alert(`تم حفظ سجل الغياب محلياً وإرساله إلى جوجل شيتس. قد تستغرق بعض الثواني لتظهر في الشيت.`);
        }, 2000);
    } else {
        alert(`تم حفظ سجل الحضور والغياب بنجاح لشعبة ${className} للحصة ${currentLesson}! (لا يوجد غائبون لإرسالهم)`);
    }
}

