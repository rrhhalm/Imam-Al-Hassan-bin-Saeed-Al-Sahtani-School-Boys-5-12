// 9. دالة تصدير تقرير الغياب إلى إكسل
// ==========================================
function exportToExcel() {
    let savedData = JSON.parse(localStorage.getItem('attendanceData')) || {};
    let absentees = [];

    for (const [studentId, status] of Object.entries(savedData)) {
        if (status === 'absent') {
            const parts = studentId.split('_');
            const className = parts[0]; 
            const lessonNum = parts[1];
            const studentName = parts.slice(3).join('_'); 
            
            absentees.push({ 
                "الصف/الشعبة": className, 
                "الحصة": `الحصة ${lessonNum}`,
                "اسم الطالب": studentName, 
                "الحالة": "غائب" 
            });
        }
    }

    if (absentees.length === 0) {
        alert("لا يوجد أي غياب مسجل لتصديره حالياً!");
        return;
    }

    absentees.sort((a, b) => a["الصف/الشعبة"].localeCompare(b["الصف/الشعبة"], undefined, {numeric: true}));

    const worksheet = XLSX.utils.json_to_sheet(absentees);
    
    worksheet['!cols'] = [
        { wch: 15 },
        { wch: 12 },
        { wch: 40 },
        { wch: 10 }
    ];

    const workbook = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(workbook, worksheet, "تقرير الغياب");

    const date = new Date();
    const dateString = `${date.getFullYear()}-${(date.getMonth()+1).toString().padStart(2, '0')}-${date.getDate().toString().padStart(2, '0')}`;

    XLSX.writeFile(workbook, `تقرير_الغياب_${dateString}.xlsx`);
}

