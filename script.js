// ==========================================
// 5. بناء واجهة الصفوف والشعب
// ==========================================
function buildClassesUI() {
    const container = document.getElementById('classes-container');
    container.innerHTML = ''; 

    const grades = [...new Set(Object.keys(studentsData).map(key => key.split('/')[0]))]
                   .sort((a, b) => parseInt(a) - parseInt(b));

    grades.forEach(grade => {
        const item = document.createElement('div');
        item.className = 'accordion-item';
        
        const header = document.createElement('div');
        header.className = 'accordion-header';
        header.innerHTML = `<span>الصف ${grade}</span> <span>▼</span>`;
        
        const content = document.createElement('div');
        content.className = 'accordion-content';
        
        const list = document.createElement('div');
        list.className = 'class-list';

        Object.keys(studentsData).filter(key => key.startsWith(grade + '/')).forEach(className => {
            const btn = document.createElement('button');
            btn.className = 'class-btn';
            btn.textContent = `شعبة ${className}`;
            
            const studentsAccordion = document.createElement('div');
            studentsAccordion.className = 'accordion-item student-accordion';
            studentsAccordion.style.display = 'none';

            const studentsHeader = document.createElement('div');
            studentsHeader.className = 'accordion-header';
            studentsHeader.innerHTML = `<span>قائمة طلاب ${className}</span> <span>▼</span>`;

            const studentsContent = document.createElement('div');
            studentsContent.className = 'accordion-content';
            
            const studentsListDiv = document.createElement('div');
            studentsListDiv.className = 'students-list';

            let savedData = JSON.parse(localStorage.getItem('attendanceData')) || {};

            studentsData[className].forEach((student, index) => {
                const studentId = `${className}_${currentLesson}_${index}_${student}`; 
                
                const row = document.createElement('div');
                row.className = 'student-row';
                
                row.innerHTML = `
                    <span class="student-name">${index + 1}. ${student}</span>
                    <div class="attendance-actions">
                        <button class="btn-present" onclick="markAttendance(this, '${studentId}', 'present')">حاضر</button>
                        <button class="btn-absent" onclick="markAttendance(this, '${studentId}', 'absent')">غائب</button>
                    </div>
                `;
                
                if (savedData[studentId]) {
                    const btns = row.querySelectorAll('button');
                    if (savedData[studentId] === 'present') btns[0].classList.add('active');
                    if (savedData[studentId] === 'absent') btns[1].classList.add('active');
                }
                
                studentsListDiv.appendChild(row);
            });

            const saveBtn = document.createElement('button');
            saveBtn.className = 'save-btn';
            saveBtn.textContent = '💾 حفظ سجل الغياب';
            saveBtn.onclick = () => saveAttendance(className);
            studentsListDiv.appendChild(saveBtn);

            studentsContent.appendChild(studentsListDiv);
            studentsAccordion.appendChild(studentsHeader);
            studentsAccordion.appendChild(studentsContent);

            btn.onclick = () => {
                document.querySelectorAll('.student-accordion').forEach(el => {
                    if (el !== studentsAccordion) el.style.display = 'none';
                });
                
                if (studentsAccordion.style.display === 'none') {
                    studentsAccordion.style.display = 'block';
                    btn.classList.add('active');
                } else {
                    studentsAccordion.style.display = 'none';
                    btn.classList.remove('active');
                }
            };

            studentsHeader.addEventListener('click', () => {
                studentsContent.classList.toggle('active');
                studentsHeader.lastElementChild.textContent = studentsContent.classList.contains('active') ? '▲' : '▼';
            });

            list.appendChild(btn);
            list.appendChild(studentsAccordion);
        });

        content.appendChild(list);
        item.appendChild(header);
        item.appendChild(content);
        container.appendChild(item);

        header.addEventListener('click', () => {
            document.querySelectorAll('.accordion-content').forEach(acc => { 
                if(acc !== content && !acc.classList.contains('students-list')) acc.classList.remove('active'); 
            });
            content.classList.toggle('active');
            header.lastElementChild.textContent = content.classList.contains('active') ? '▲' : '▼';
        });
    });
}

function markAttendance(btnElement, studentId, status) {
    const parent = btnElement.parentElement;
    parent.querySelectorAll('button').forEach(btn => btn.classList.remove('active'));
    btnElement.classList.add('active');
    
    let tempData = JSON.parse(sessionStorage.getItem('tempAttendance')) || {};
    tempData[studentId] = status;
    sessionStorage.setItem('tempAttendance', JSON.stringify(tempData));
}

